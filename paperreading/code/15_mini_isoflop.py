import sys,json,time,numpy as np
V=16;L=24;B=32
RNG=np.random.default_rng(12345);TAB=RNG.integers(0,V,(V,V,3));W3=RNG.dirichlet([1,1,1],(V,V))
ENT=float(np.mean(-(W3*np.log(W3)).sum(-1)))
def gen(r,n,l=L+1):
    x=np.zeros((n,l),int);x[:,:2]=r.integers(0,V,(n,2))
    for t in range(2,l):
        a,b=x[:,t-2],x[:,t-1];c=(W3[a,b].cumsum(1)>r.random((n,1))).argmax(1);x[:,t]=TAB[a,b,c]
    return x
def nparam(m):return int(sum(p.v.size for p in m.ps))
def run(d,C,seed,mult=1.,lr0=None):
    h=max(2,d//8);m=Enc(V,L,d=d,h=h,ff=2*d,N=2,seed=seed,causal=True);N=nparam(m);D=C/(6*N);steps=max(10,int(D/(B*L)));o=Adam(m.ps);r=np.random.default_rng(seed+1000);cyc=steps*mult;t0=time.time();lr0=lr0 or 2e-3
    for st in range(1,steps+1):
        x=gen(r,B);X,Y=x[:,:-1],x[:,1:];v,p,g=ce(m.lm(X),Y);p.backward(g);lr=lr0*min(1,st/(.1*steps+1))*(.1+.9*.5*(1+np.cos(np.pi*min(st/cyc,1))))
        o.step(lr)
    ev=np.random.default_rng(777);ls=[]
    for _ in range(8):
        x=gen(ev,100);ls.append(ce(m.lm(x[:,:-1]),x[:,1:])[0])
    return dict(d=d,N=N,D=steps*B*L,C=C,steps=steps,loss=float(np.mean(ls)),sec=round(time.time()-t0,1),mult=mult)
